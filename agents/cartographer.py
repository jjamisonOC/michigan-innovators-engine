class MichiganCartographerAgent:
    """
    Agent 1: Discovers, geocodes, deduplicates, and normalizes Michigan startup support
    organizations across all 10 Prosperity Regions and syncs them to Supabase.
    """

    def __init__(self, user_agent: str = "michigan-startup-ecosystem-intelligence-engine/1.0"):
        self.user_agent = user_agent

    async def geocode_address(
        self, client: httpx.AsyncClient, address: str, city: str
    ) -> Optional[Dict[str, float]]:
        """
        Queries OpenStreetMap Nominatim to resolve a physical Michigan address into
        exact latitude/longitude coordinates when not already present.
        """
        query = f"{address}, Michigan, USA" if "MI" not in address else address
        url = f"https://nominatim.openstreetmap.org/search?q={quote_plus(query)}&format=json&limit=1"
        try:
            resp = await client.get(url, headers={"User-Agent": self.user_agent}, timeout=10.0)
            if resp.status_code == 200:
                results = resp.json()
                if results:
                    return {
                        "latitude": round(float(results[0]["lat"]), 6),
                        "longitude": round(float(results[0]["lon"]), 6),
                    }
        except Exception as exc:
            logger.debug("Nominatim lookup failed for %s (%s): %s", city, address, exc)
        return None

    async def verify_and_enrich_seed(
        self, client: httpx.AsyncClient, org: Dict[str, Any], semaphore: asyncio.Semaphore
    ) -> Dict[str, Any]:
        """
        Verifies coordinates (geocoding via Nominatim if missing) and optionally inspects
        homepage meta description / contact email to enrich the seed record.
        """
        async with semaphore:
            enriched = dict(org)
            if enriched.get("latitude") is None or enriched.get("longitude") is None:
                coords = await self.geocode_address(
                    client, enriched.get("address", ""), enriched.get("city", "")
                )
                if coords:
                    enriched["latitude"] = coords["latitude"]
                    enriched["longitude"] = coords["longitude"]

            enriched["last_quarterly_scrape"] = datetime.now(timezone.utc).isoformat()
            return TaxonomyNormalizerAgent.normalize_organization(enriched)

    async def run(
        self,
        output_json_path: Optional[str] = "michigan_seed_list.json",
        max_concurrency: int = 8,
    ) -> List[Dict[str, Any]]:
        """
        Executes Agent 1: compiles the deduplicated Michigan ecosystem master list,
        geocodes any missing coordinates, normalizes tags via Agent 4, and writes
        `michigan_seed_list.json`.
        """
        semaphore = asyncio.Semaphore(max_concurrency)
        async with httpx.AsyncClient(
            follow_redirects=True,
            headers={"User-Agent": self.user_agent},
            timeout=15.0,
        ) as client:
            tasks = [
                self.verify_and_enrich_seed(client, seed, semaphore)
                for seed in MICHIGAN_ECOSYSTEM_MASTER_SEEDS
            ]
            verified_orgs = await asyncio.gather(*tasks)

        deduped = TaxonomyNormalizerAgent.normalize_batch(list(verified_orgs))

        if output_json_path:
            out_path = Path(output_json_path)
            out_path.write_text(json.dumps(deduped, indent=2), encoding="utf-8")
            logger.info(
                "Agent 1 (Cartographer) wrote %d organizations to %s",
                len(deduped),
                out_path.resolve(),
            )

        return deduped
